import 'package:devnotes/l10n/app_localizations.dart';

/// Tên dễ đọc của một công cụ soạn thảo (thay cho id nội bộ như
/// `code_inline`), theo ngôn ngữ đang chọn. Cũng là tooltip của nút.
String editorToolLabel(AppLocalizations l, String id) => switch (id) {
  'h1' => l.toolbarItemH1,
  'h2' => l.toolbarItemH2,
  'h3' => l.toolbarItemH3,
  'bold' => l.toolbarItemBold,
  'italic' => l.toolbarItemItalic,
  'strikethrough' => l.toolbarItemStrikethrough,
  'link' => l.toolbarItemLink,
  'image' => l.toolbarItemImage,
  'code_inline' => l.toolbarItemCodeInline,
  'code_block' => l.toolbarItemCodeBlock,
  'checklist' => l.toolbarItemChecklist,
  'list_unordered' => l.toolbarItemListUnordered,
  'list_ordered' => l.toolbarItemListOrdered,
  'quote' => l.toolbarItemQuote,
  'table' => l.toolbarItemTable,
  'hr' => l.toolbarItemHr,
  'font' => l.editorToolFont,
  'size_down' => l.editorToolSizeDown,
  'size_up' => l.editorToolSizeUp,
  'line_height' => l.editorToolLineHeight,
  'word_wrap' => l.editorToolWordWrap,
  'focus_mode' => l.editorToolFocusMode,
  'theme' => l.editorToolTheme,
  'undo' => l.editorToolUndo,
  'redo' => l.editorToolRedo,
  'indent' => l.editorToolIndent,
  'outdent' => l.editorToolOutdent,
  'move_up' => l.editorToolMoveUp,
  'move_down' => l.editorToolMoveDown,
  'duplicate_line' => l.editorToolDuplicateLine,
  'delete_line' => l.editorToolDeleteLine,
  'find_replace' => l.editorToolFindReplace,
  'date_time' => l.editorToolDateTime,
  'symbols' => l.editorToolSymbols,
  'note_link' => l.editorToolNoteLink,
  'template' => l.editorToolTemplate,
  'outline' => l.editorToolOutline,
  'stats' => l.editorToolStats,
  _ => id,
};
